#!/usr/bin/env python3
"""Translation housekeeping (docs/TRANSLATIONS.md).

  tools/l10n.py sync    Write the shipped languages (app/lib/l10n/shipped_locales.dart) into
                        Android's res/xml/locales_config.xml and iOS's CFBundleLocalizations.
  tools/l10n.py check   Fail if those are out of step, if an ARB file is malformed, or if a
                        shipped language is below the bar (decision D5). Run in CI.
  tools/l10n.py stats   Print each translation's coverage.

The bar (D5): every message marked [medical] or [legal] in its description, and every report and
notification message (keys starting with "report" or "notif"), is translated; and at least 90% of
all messages are. Whether Weblate reviewers approved them is checked in Weblate, not here.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / 'app'
L10N = APP / 'lib' / 'l10n'
SHIPPED = L10N / 'shipped_locales.dart'
LOCALES_CONFIG = APP / 'android' / 'app' / 'src' / 'main' / 'res' / 'xml' / 'locales_config.xml'
INFO_PLIST = APP / 'ios' / 'Runner' / 'Info.plist'
TEMPLATE = 'en'
MIN_SHARE = 0.90
REQUIRED_PREFIXES = ('report', 'notif')
REQUIRED_TAGS = ('[medical]', '[legal]')


def shipped():
    """Locale tags from kShippedLocales, e.g. ['en', 'fr', 'zh-Hans'], in order."""
    text = SHIPPED.read_text()
    body = text[text.index('kShippedLocales'):]
    tags = []
    for m in re.finditer(
            r"Locale\('([a-z]{2,3})'(?:,\s*'([A-Z]{2})')?\)"
            r"|Locale\.fromSubtags\(([^)]*)\)", body):
        if m.group(1):
            tags.append(m.group(1) + (f'-{m.group(2)}' if m.group(2) else ''))
        else:
            args = dict(re.findall(r"(\w+):\s*'([^']*)'", m.group(3)))
            tags.append('-'.join(v for v in (args.get('languageCode'), args.get('scriptCode'),
                                             args.get('countryCode')) if v))
    if not tags or tags[0] != TEMPLATE:
        sys.exit(f'{SHIPPED}: English must be listed first')
    return tags


def arb_name(tag):
    """'zh-Hans' -> 'zh_Hans', the ARB file suffix."""
    return tag.replace('-', '_')


def load(path):
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError as e:
        sys.exit(f'{path}: invalid JSON: {e}')


def messages(arb):
    return {k: v for k, v in arb.items() if not k.startswith('@')}


def placeholders(text):
    """Placeholder names in an ICU message, ignoring plural/select case labels."""
    return set(re.findall(r'\{(\w+)(?=[},])', text))


def locales_config_xml(tags):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by tools/l10n.py sync from app/lib/l10n/shipped_locales.dart. -->',
             '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">']
    lines += [f'    <locale android:name="{t}"/>' for t in tags]
    lines += ['</locale-config>', '']
    return '\n'.join(lines)


PLIST_KEY = '\t<key>CFBundleLocalizations</key>\n'


def plist_with(text, tags):
    block = PLIST_KEY + '\t<array>\n' + ''.join(
        f'\t\t<string>{t}</string>\n' for t in tags) + '\t</array>\n'
    if PLIST_KEY in text:
        return re.sub(r'\t<key>CFBundleLocalizations</key>\n\t<array>\n(?:\t\t<string>[^<]*</string>\n)*\t</array>\n',
                      lambda _: block, text)
    anchor = '\t<key>CFBundleDisplayName</key>\n'
    if anchor not in text:
        sys.exit(f'{INFO_PLIST}: CFBundleDisplayName not found')
    return text.replace(anchor, block + anchor, 1)


def sync():
    tags = shipped()
    LOCALES_CONFIG.write_text(locales_config_xml(tags))
    INFO_PLIST.write_text(plist_with(INFO_PLIST.read_text(), tags))
    print('shipped:', ', '.join(tags))


def coverage(template, arb):
    tmsg, msg = messages(template), messages(arb)
    done = {k for k, v in msg.items() if k in tmsg and v.strip()}
    required = {k for k in tmsg
                if k.startswith(REQUIRED_PREFIXES)
                or any(t in template.get('@' + k, {}).get('description', '') for t in REQUIRED_TAGS)}
    return len(done) / len(tmsg), sorted(required - done)


def check():
    errors = []
    template = load(L10N / f'app_{TEMPLATE}.arb')
    tmsg = messages(template)
    for k in tmsg:
        if not template.get('@' + k, {}).get('description'):
            errors.append(f'app_{TEMPLATE}.arb: "{k}" has no description for translators')
    for path in sorted(L10N.glob('app_*.arb')):
        if path.name == f'app_{TEMPLATE}.arb':
            continue
        for k, v in messages(load(path)).items():
            if k not in tmsg:
                errors.append(f'{path.name}: "{k}" is not in the English template')
            elif placeholders(v) - placeholders(tmsg[k]):
                errors.append(f'{path.name}: "{k}" uses placeholders the English text lacks: '
                              f'{sorted(placeholders(v) - placeholders(tmsg[k]))}')
    tags = shipped()
    for tag in tags[1:]:
        path = L10N / f'app_{arb_name(tag)}.arb'
        if not path.exists():
            errors.append(f'{tag} is shipped but {path.name} does not exist')
            continue
        share, missing = coverage(template, load(path))
        if share < MIN_SHARE:
            errors.append(f'{tag} is shipped but only {share:.0%} translated (bar: {MIN_SHARE:.0%})')
        if missing:
            errors.append(f'{tag} is shipped but these required messages are missing: '
                          + ', '.join(missing[:10]) + (' …' if len(missing) > 10 else ''))
    if not LOCALES_CONFIG.exists() or LOCALES_CONFIG.read_text() != locales_config_xml(tags):
        errors.append(f'{LOCALES_CONFIG.relative_to(ROOT)} is out of step: run tools/l10n.py sync')
    plist = INFO_PLIST.read_text()
    if plist_with(plist, tags) != plist:
        errors.append(f'{INFO_PLIST.relative_to(ROOT)} CFBundleLocalizations is out of step: '
                      'run tools/l10n.py sync')
    for e in errors:
        print('error:', e)
    if errors:
        sys.exit(1)
    print(f'ok: {len(tmsg)} messages; shipped: {", ".join(tags)}')


def stats():
    template = load(L10N / f'app_{TEMPLATE}.arb')
    tags = shipped()
    print(f'{TEMPLATE}: {len(messages(template))} messages (template)')
    for path in sorted(L10N.glob('app_*.arb')):
        if path.name == f'app_{TEMPLATE}.arb':
            continue
        tag = path.stem[4:].replace('_', '-')
        share, missing = coverage(template, load(path))
        state = 'shipped' if tag in tags else 'not shipped'
        print(f'{tag}: {share:.0%} translated, {len(missing)} required missing ({state})')


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    {'sync': sync, 'check': check, 'stats': stats}.get(cmd, lambda: sys.exit(__doc__))()
